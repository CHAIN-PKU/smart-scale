/**
  ******************************************************************************
  * @file    config.h
  * @brief   整份固件里需要你手动改的东西，全都集中在这一个文件里。
  *          接线、量程、标定系数、主频，改这里就够了，别的文件不用动。
  ******************************************************************************
  */

#ifndef __CONFIG_H
#define __CONFIG_H

#include "stm32f1xx_hal.h"

/*==============================================================================
 * 1. HX711 接线
 *    接好线以后，把这两个引脚号报给软件那边。
 *    TFT 占用 PB9~PB15，所以 HX711 改用 PB0 / PB1。
 *============================================================================*/
#define HX711_DT_PORT            GPIOB
#define HX711_DT_PIN             GPIO_PIN_0       /* HX711 的 DT / DOUT  -> 单片机输入 */
#define HX711_SCK_PORT           GPIOB
#define HX711_SCK_PIN            GPIO_PIN_1       /* HX711 的 SCK / PD_SCK -> 单片机输出 */

/*==============================================================================
 * 1.5 去皮按键（本地手动去皮，板子上的 K1）
 *    当前用的是 PA1。接线：K1 一端接 GND，另一端接 PA1。
 *    （PA9/PA10 给了串口，PB0/PB1 给了 HX711，PA1 不冲突。）
 *
 *    TARE_KEY_ACTIVE_LOW：
 *      1 = 按下时该脚被拉到地（最常见，配合内部上拉）
 *      0 = 按下时该脚被拉到高电平（配合内部下拉）
 *============================================================================*/
#define TARE_KEY_PORT            GPIOA
#define TARE_KEY_PIN             GPIO_PIN_1
#define TARE_KEY_ACTIVE_LOW      1
#define TARE_KEY_DEBOUNCE_MS     30U             /* 消抖时间 */

/*==============================================================================
 * 1.6 清单功能按键
 *    SW2 -> PE6：保存当前一笔
 *    SW3 -> PE7：打开清单
 *    SW4 -> PC6：清空清单
 *    三个键均为另一端接 GND，低电平表示按下。
 *============================================================================*/
#define SAVE_KEY_PORT            GPIOE
#define SAVE_KEY_PIN             GPIO_PIN_6
#define RECEIPT_KEY_PORT         GPIOE
#define RECEIPT_KEY_PIN          GPIO_PIN_7
#define CLEAR_KEY_PORT           GPIOC
#define CLEAR_KEY_PIN            GPIO_PIN_6
#define ACTION_KEY_DEBOUNCE_MS   100U
#define ACTION_KEY_LOCKOUT_MS    250U

/*==============================================================================
 * 2. 传感器量程
 *    买好传感器以后填这里。软件那边按满量程的 90% 算过载线。
 *    5kg 传感器 -> 5000.0f      10kg 传感器 -> 10000.0f
 *    量程没定之前，先别乱填一个很大的数。
 *============================================================================*/
#define SCALE_FULL_SCALE_G       5000.0f
#define SCALE_OVERLOAD_RATIO     0.9f          /* 满量程的 90% 算过载 */

/*==============================================================================
 * 3. 标定系数  —— 必须拿已知重量的东西实测，方法见 README.md
 *    CALIB_ZERO_RAW     : 空秤时 HX711 的原始读数
 *    CALIB_COUNTS_PER_G : 每 1 克对应多少个原始读数
 *    按文档要求，偏移先给 0，标定完再把实测值填回来。
 *============================================================================*/
#define CALIB_ZERO_RAW           (-411362L)
#define CALIB_COUNTS_PER_G       438.71f

/*==============================================================================
 * 4. 状态判断阈值（按文档给的数，一般不用改）
 *============================================================================*/
#define ZERO_THRESHOLD_G         2.0f          /* 空秤：净重绝对值 <= 2 克 */
#define STABLE_TOLERANCE_G       0.5f          /* 稳定：波动 <= 0.5 克 */
#define STABLE_TIME_MS           500U          /* 稳定要连续保持约 0.5 秒 */
#define HX711_TIMEOUT_MS         1000U         /* 1 秒读不到新样本 -> ERROR */
#define TARE_SAMPLE_COUNT        10            /* 去皮：连续取 10 个新样本求平均 */
#define TARE_TIMEOUT_MS          3000U         /* 取满 10 个样本的时间上限 */

/*==============================================================================
 * 5. 主频
 *    默认 0：用芯片内部 HSI，36MHz，不依赖任何外部晶振，一定能跑起来。
 *    改成 1：用外部 8MHz 晶振，72MHz。
 *    ！只有晶振确实是 8MHz 才能改成 1，否则主频会错、串口会乱码。
 *============================================================================*/
#define USE_HSE_8M_CLOCK         0

/*==============================================================================
 * 5.5 语音模块（CN-TTS 中文语音合成）
 *    接在 USART2：PA2 = 板子发(TX) -> 模块 RX；PA3 = 板子收(RX) <- 模块 TX
 *    9600 8N1，直接发 GBK 文本，模块自己合成语音（发什么念什么）。
 *
 *    VOICE_TEST_SENTENCE：1 = 上电念一句"欢迎使用智能电子秤"验接线；验完改 0。
 *    VOICE_VOLUME：1~4（默认 4 = 最大）
 *    VOICE_SPEED ：1~3（默认 2 = 中速）
 *============================================================================*/
#define VOICE_TEST_SENTENCE      0
#define VOICE_VOLUME             4
#define VOICE_SPEED              2

/*  重量稳定后是否直接用语音报克数（1 = 报，0 = 只等电脑回价格再报）
 *  按软件同学的文档，正式行为是 0：等电脑回了价格，再念"商品名+克数+金额" */
#define VOICE_ANNOUNCE_WEIGHT    0

/*==============================================================================
 * 5.6 WiFi 模块（ESP-01，插在板子上标着 ESP8266 的座子）
 *    这块板的排针没有 PC10、PC11。固件用 USART3 完全重映射：
 *    PD8 发送到模块 RX，PD9 接收模块 TX。115200 8N1。
 *    模块自己开一个热点，手机连上以后打开 http://192.168.4.1/records
 *    或 http://192.168.4.1/receipt 。记录仍由电脑查数据库后答回来。
 *    座子若不是这组脚，只改下面四个宏。WIFI_ENABLE 改 0 就完全不碰这组串口。
 *============================================================================*/
#define WIFI_ENABLE              1
#define WIFI_TX_PORT             GPIOD
#define WIFI_TX_PIN              GPIO_PIN_8
#define WIFI_RX_PORT             GPIOD
#define WIFI_RX_PIN              GPIO_PIN_9
#define WIFI_AP_NAME             "SmartScale"
#define WIFI_AP_PASS             "12345678"

/*==============================================================================
 * 6. 调试开关
 *    标定的时候把 DEBUG_PRINT_RAW 打开，串口上会多打一行 "# RAW=xxxxx"，
 *    那一行不是 JSON，电脑会自动忽略，不会影响协议。
 *============================================================================*/
#define DEBUG_PRINT_RAW          0             /* 1 = 每次采样打印原始读数，标定用 */

/*  串口回显调试：
 *  1 = 每收到一整行，就原样回显一行 "# RX n bytes: ..."（非 JSON，电脑会忽略）
 *  用来确认"板子到底有没有收到电脑发来的数据"。平时保持 0。            */
#define DEBUG_ECHO_RX            0

/*  串口收字节计数心跳：
 *  1 = 每秒打一行 "# HB rx=<累计收到> err=<错误次数> tx=<累计发出>"（非 JSON）
 *  用来一眼看出板子到底有没有收到数据。平时保持 0。                     */
#define DEBUG_RX_COUNTER         0


/*  weight 行里 stable 字段的含义：
 *  0 = 只要读数物理上稳住了就是 true（字面含义，默认）
 *  1 = 只有处于 WEIGHT_STABLE 状态才是 true（更保守）            */
#define WEIGHT_STABLE_FLAG_ONLY_WHEN_LOADED   0

#endif /* __CONFIG_H */
